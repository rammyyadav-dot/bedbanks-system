async function login(browser) {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } })
  const page = await ctx.newPage()
  page.setDefaultTimeout(15000)
  await page.goto(`${AGENT}/login`)
  await page.fill('#email', seed.homeAgentEmail ?? seed.agentEmail); await page.fill('#password', seed.password)
  await page.locator('button[type=submit]').click()
  if (seed.homeAgentEmail) { await page.waitForSelector('#active-workspace', { timeout: 30000 }); await page.locator('#active-workspace').selectOption(seed.tenantA) }
  await page.waitForSelector('#hotel-search', { timeout: 30000 })
  return { ctx, page }
}
async function bounds(page, selector) {
  const rect = await page.locator(selector).boundingBox()
  expect(rect.x).toBeGreaterThanOrEqual(0); expect(rect.y).toBeGreaterThanOrEqual(0)
  expect(rect.x + rect.width).toBeLessThanOrEqual(page.viewportSize().width + 1)
  expect(rect.y + rect.height).toBeLessThanOrEqual(page.viewportSize().height + 1)
}

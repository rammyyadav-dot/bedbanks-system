// Real-stack browser verification of the Agent search thumbnail (ADR 0027). See README.md. Not run in CI.
const path = require('path')
const { createRequire } = require('module')
const req = createRequire(path.join(__dirname, '../../apps/website/package.json'))
const { chromium } = req('@playwright/test')
const seed = require(process.env.SEED_JSON ?? path.join(__dirname, '.seed-agent-images.json'))
const BASE = process.env.AGENT_URL ?? 'http://localhost:3003'
const results = []
const check = (name, ok, extra = '') => { results.push({ name, ok: !!ok }); console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${extra ? '  — ' + String(extra).slice(0, 160) : ''}`) }

;(async () => {
  const browser = await chromium.launch()
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } }); const page = await ctx.newPage()
  const failedImages = []
  page.on('response', (r) => { if (/\/agent\/hotels\/.+\/images\//.test(r.url()) && !r.ok()) failedImages.push(r.status()) })
  await page.goto(`${BASE}/login`)
  await page.fill('#email', seed.agentEmail); await page.fill('#password', seed.password)
  await page.click('button[type=submit]')
  await page.waitForSelector('#hotel-search', { timeout: 30000 })
  await page.getByLabel('Destination').click(); await page.getByLabel('Destination').fill('Dubai')
  await page.getByRole('option', { name: /Dubai/ }).first().click()
  const day = (n) => new Date(Date.now() + n * 86_400_000).toISOString().slice(0, 10)
  await page.locator('.market-field:has(> span:text-is("Stay")) button.market-control').click()
  await page.getByLabel('Check-in').fill(day(10)); await page.getByLabel('Check-out').fill(day(12))
  await page.getByRole('button', { name: /^Search/ }).first().click()
  await page.waitForSelector('article.market-hotel-card', { timeout: 30000 })
  const cards = page.locator('article.market-hotel-card')
  check('both published hotels are listed', (await cards.count()) === 2)
  const withPic = cards.filter({ hasText: seed.names.pic }); const without = cards.filter({ hasText: seed.names.nopic })
  await withPic.getByTestId('hotel-thumbnail').waitFor({ timeout: 15000 })
  check('the hotel with an image shows a thumbnail with its alt text', (await withPic.locator('img').getAttribute('alt')) === 'Blue pool deck')
  check('the browser decoded the bytes served by the Agent route (800x600)', await withPic.locator('img').evaluate((el) => el.complete && el.naturalWidth === 800 && el.naturalHeight === 600))
  check('the hotel without an image shows the initial mark and no picture', (await without.getByTestId('hotel-thumbnail').count()) === 0 && (await without.locator('img').count()) === 0 && /^B/.test((await without.locator('.market-hotel-mark').innerText()).trim()))
  await cards.first().scrollIntoViewIfNeeded(); await page.locator('article.market-hotel-card').first().locator('xpath=..').screenshot({ path: process.env.SHOT_CARDS ?? path.join(require('os').tmpdir(), 'agent-cards.png') })
  check('no image request failed', failedImages.length === 0, failedImages.join(','))
  await withPic.getByRole('button', { name: /View rooms/ }).click()
  await page.waitForSelector('.market-detail-head', { timeout: 15000 })
  await page.locator('.market-detail-head [data-testid=hotel-thumbnail] img').waitFor({ timeout: 15000 })
  check('the hotel detail header shows the same image', await page.locator('.market-detail-head img').evaluate((el) => el.complete && el.naturalWidth === 800))
  check('no horizontal overflow on desktop', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
  await page.setViewportSize({ width: 390, height: 800 })
  check('no horizontal overflow on a phone', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
  await page.screenshot({ path: process.env.SHOT ?? path.join(require('os').tmpdir(), 'agent-thumbnail.png'), fullPage: false })
  await ctx.close(); await browser.close()
  const failed = results.filter((r) => !r.ok)
  console.log(`\n${results.length - failed.length}/${results.length} checks passed`)
  process.exit(failed.length ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })

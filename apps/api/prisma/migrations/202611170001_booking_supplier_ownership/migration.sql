-- Remove the extranet bookings routes first. No booking row is deleted by the rollback.

ALTER TABLE "Booking" ADD COLUMN "supplier_id" TEXT;

ALTER TABLE "Booking" ADD CONSTRAINT "Booking_tenant_id_supplier_id_fkey"
  FOREIGN KEY ("tenant_id", "supplier_id") REFERENCES "Supplier"("tenant_id", "id") ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE INDEX "Booking_tenant_id_supplier_id_created_at_idx" ON "Booking"("tenant_id", "supplier_id", "created_at");
CREATE INDEX "Booking_tenant_id_supplier_id_status_idx" ON "Booking"("tenant_id", "supplier_id", "status");
CREATE INDEX "Booking_tenant_id_supplier_id_check_in_idx" ON "Booking"("tenant_id", "supplier_id", "check_in");

CREATE FUNCTION "Booking_supplier_id_immutable"() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD."supplier_id" IS NOT NULL AND NEW."supplier_id" IS DISTINCT FROM OLD."supplier_id" THEN
    RAISE EXCEPTION 'Booking.supplier_id is immutable once set' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "Booking_supplier_id_immutable" BEFORE UPDATE OF "supplier_id" ON "Booking"
  FOR EACH ROW EXECUTE FUNCTION "Booking_supplier_id_immutable"();

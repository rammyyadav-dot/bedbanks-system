-- ADR 0061 Amendment 1: Booking.supplier_id, the supplier organization that owns a contracted-inventory booking.
--
-- Additive and nullable: no existing row changes and no row is attributed here (historical attribution is the separate, reviewed, dry-run-first
-- backfill CLI `ops:backfill-booking-supplier`). Null means "no supplier organization": connector, manual and unattributable bookings.
--
-- Safeguards
--   * Composite foreign key (tenant_id, supplier_id) -> "Supplier"(tenant_id, id): a booking can only point at a supplier of its own tenant.
--     MATCH SIMPLE leaves the constraint inactive while supplier_id is null. ON DELETE RESTRICT: a supplier with bookings can never be deleted
--     (and the cascade from Tenant/Supplier cannot remove a booking through this path).
--   * Immutability trigger: once supplier_id is non-null it cannot change or be cleared, by any role. Null -> value is allowed once.
--
-- Tenant-index review: every extranet read filters (tenant_id, supplier_id) and orders by created_at, or filters by status / check_in.
--   (tenant_id, supplier_id, created_at)  list and cursor order
--   (tenant_id, supplier_id, status)      status filter
--   (tenant_id, supplier_id, check_in)    arrival-date filter
--
-- Rollback is a later forward migration. Do not edit this file after it is applied.
--   DROP TRIGGER IF EXISTS "Booking_supplier_id_immutable" ON "Booking";
--   DROP FUNCTION IF EXISTS "Booking_supplier_id_immutable"();
--   DROP INDEX IF EXISTS "Booking_tenant_id_supplier_id_check_in_idx", "Booking_tenant_id_supplier_id_status_idx", "Booking_tenant_id_supplier_id_created_at_idx";

-- Approval request expiry (ADR 0095). A request that is not decided, or an approval that is not executed, within the configured TTL
-- (APPROVAL_TTL_HOURS, default 72) becomes EXPIRED. The service moves it with a conditional update, so a concurrent decision still wins.
--
-- No new table, column, index or grant: ApprovalRequest keeps its forced tenant RLS and its (tenant_id, status) index, which serves the
-- expiry sweep. Only the status enum and the decision-completeness CHECK change.
--
-- The new CHECK branch compares "status"::text, not the enum literal: PostgreSQL does not allow a value added by ALTER TYPE ... ADD VALUE
-- to be used inside the same transaction, and Prisma runs a migration in one transaction.
--
-- Rollback is a later forward migration; an enum value cannot be dropped in place. Do not edit this file after it is applied.
--   1. UPDATE "ApprovalRequest" SET "status" = 'CANCELLED' WHERE "status"::text = 'EXPIRED';
--   2. restore the previous CHECK (see 202610080001_approval_requests) with ALTER TABLE ... DROP/ADD CONSTRAINT
--   3. recreate the enum without EXPIRED and re-point the column (ALTER TYPE ... RENAME, CREATE TYPE, ALTER COLUMN ... USING)

ALTER TYPE "ApprovalRequestStatus" ADD VALUE IF NOT EXISTS 'EXPIRED';

ALTER TABLE "ApprovalRequest" DROP CONSTRAINT "ApprovalRequest_decision_complete";
ALTER TABLE "ApprovalRequest" ADD CONSTRAINT "ApprovalRequest_decision_complete" CHECK (
  ("status" = 'PENDING' AND "decided_by_id" IS NULL AND "decided_at" IS NULL)
  OR ("status" = 'CANCELLED')
  OR ("status" IN ('APPROVED', 'REJECTED') AND "decided_by_id" IS NOT NULL AND "decided_at" IS NOT NULL AND "executed_at" IS NULL)
  OR ("status" = 'EXECUTED' AND "decided_by_id" IS NOT NULL AND "decided_at" IS NOT NULL AND "executed_by_id" IS NOT NULL AND "executed_at" IS NOT NULL)
  OR ("status"::text = 'EXPIRED' AND "executed_at" IS NULL AND ("decided_by_id" IS NULL) = ("decided_at" IS NULL))
);

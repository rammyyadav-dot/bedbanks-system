-- Percent markup rules for NET daily rates (ADR 0018).
-- Rules are immutable except for status: DRAFT -> ACTIVE (only through an approved maker-checker request),
-- ACTIVE or DRAFT -> RETIRED. At most one ACTIVE rule exists per (tenant, scope, supplier, hotel); that is a
-- partial unique index, which Prisma cannot model, so `prisma migrate diff` will list it like the pgvector HNSW index.
-- basis_points is an integer 0..10000. Scope and target must agree. Money is never stored as a float.
--
-- Tenant indexes: (tenant_id, status) for the rule list and rule resolution, (tenant_id, scope, supplier_id, hotel_id) for lookups.
--
-- The conditional GRANT below mirrors "SupplierMutation" and "ApprovalRequest". It is a production privilege change in
-- effect, so it needs the ADR 0013 human decision before this migration is applied to any persistent environment.
-- Rule resolution by the Agent search needs SELECT for the API runtime role, so that grant is part of the same decision.
--
-- Rollback is a later forward migration. Do not edit this file after it is applied.

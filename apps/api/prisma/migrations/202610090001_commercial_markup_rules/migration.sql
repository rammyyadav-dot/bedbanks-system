--   DROP TYPE IF EXISTS "MarkupScope";

-- CreateEnum
CREATE TYPE "MarkupScope" AS ENUM ('TENANT_DEFAULT', 'SUPPLIER', 'HOTEL');

-- CreateEnum
CREATE TYPE "MarkupRuleStatus" AS ENUM ('DRAFT', 'ACTIVE', 'RETIRED');

-- CreateTable
CREATE TABLE "CommercialMarkupRule" (
    "id" TEXT NOT NULL,
    "tenant_id" TEXT NOT NULL,
    "scope" "MarkupScope" NOT NULL,
    "supplier_id" TEXT,
    "hotel_id" TEXT,
    "basis_points" INTEGER NOT NULL,
    "valid_from" DATE NOT NULL,
    "valid_to" DATE,
    "status" "MarkupRuleStatus" NOT NULL DEFAULT 'DRAFT',
    "reason" TEXT NOT NULL,
    "created_by_id" TEXT NOT NULL,
    "activated_at" TIMESTAMP(3),
    "retired_at" TIMESTAMP(3),
    "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMP(3) NOT NULL,

    CONSTRAINT "CommercialMarkupRule_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "CommercialMarkupRule_basis_points_range" CHECK ("basis_points" >= 0 AND "basis_points" <= 10000),
    CONSTRAINT "CommercialMarkupRule_validity_order" CHECK ("valid_to" IS NULL OR "valid_to" >= "valid_from"),
    CONSTRAINT "CommercialMarkupRule_scope_target" CHECK (
      ("scope" = 'TENANT_DEFAULT' AND "supplier_id" IS NULL AND "hotel_id" IS NULL)
      OR ("scope" = 'SUPPLIER' AND "supplier_id" IS NOT NULL AND "hotel_id" IS NULL)
      OR ("scope" = 'HOTEL' AND "hotel_id" IS NOT NULL AND "supplier_id" IS NULL)
    ),
    CONSTRAINT "CommercialMarkupRule_status_timestamps" CHECK (
      ("status" = 'DRAFT' AND "activated_at" IS NULL AND "retired_at" IS NULL)
      OR ("status" = 'ACTIVE' AND "activated_at" IS NOT NULL AND "retired_at" IS NULL)
      OR ("status" = 'RETIRED' AND "retired_at" IS NOT NULL)
    )
);

-- CreateIndex
CREATE INDEX "CommercialMarkupRule_tenant_id_status_idx" ON "CommercialMarkupRule"("tenant_id", "status");

-- CreateIndex
CREATE INDEX "CommercialMarkupRule_tenant_id_scope_supplier_id_hotel_id_idx" ON "CommercialMarkupRule"("tenant_id", "scope", "supplier_id", "hotel_id");

-- At most one ACTIVE rule per target.
CREATE UNIQUE INDEX "CommercialMarkupRule_one_active_per_target" ON "CommercialMarkupRule"("tenant_id", "scope", COALESCE("supplier_id", ''), COALESCE("hotel_id", '')) WHERE "status" = 'ACTIVE';


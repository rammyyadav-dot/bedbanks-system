-- Partner authentication context and OAuth token issuance (ADR 0075, amendment 4: step 2 of the distribution login).
--
-- 1. The two lookup functions from 202611290001 now also return what the guard needs right after authenticating, so a request costs one
--    round trip and the runtime still needs no table privilege: the client's CIDR allowlist and its per-minute limits (the quotas in step 3).
--    Their return type changes, so they are dropped and recreated (CREATE OR REPLACE cannot change OUT columns).
-- 2. fbeds_distribution_issue_token(key_id, secret_hash, token_hash, scopes, ttl_seconds, request_id) issues an OAuth access token. It re-verifies the
--    OAuth client secret itself, so even a compromised API process cannot mint a token without a real client secret, and it inserts the
--    token and its audit event in one statement's transaction: both or neither (invariant 8). Results:
--      no row                    the client did not authenticate (unknown, wrong secret, revoked, expired, not OAUTH_CLIENT, inactive)
--      outcome 'invalid_scope'   authenticated, but asked for a scope the client does not hold; nothing is written
--      outcome 'issued'          token written (hash only) with its audit event
--    ttl_seconds is 60 to 900 here (the table allows up to an hour); requested scopes empty or NULL means all of the client's scopes.
--
-- All three are SECURITY DEFINER with a pinned search_path and are not executable by PUBLIC. EXECUTE for the API runtime comes only from
-- runtime-role-contract.ts (RUNTIME_FUNCTION_GRANTS), applied by `ops:provision-api-runtime-role`. Dropping a function drops its grants, so
-- run provisioning after deploying this migration; until then partner authentication is refused (fail closed).
--
-- Like the functions they replace, they rely on the migration owner bypassing forced RLS; without it they return no row (fail closed).
-- No table, column, policy or grant changes. No tenant index changes.
--
-- Rollback is a later forward migration; do not edit this file once applied:
--   DROP FUNCTION "fbeds_distribution_issue_token"(TEXT, TEXT, TEXT, "DistributionApiScope"[], INTEGER, TEXT);
--   then recreate the two lookup functions exactly as in 202611290001_distribution_credentials, and re-run provisioning.

DROP FUNCTION "fbeds_distribution_authenticate_key"(TEXT, TEXT);
DROP FUNCTION "fbeds_distribution_authenticate_token"(TEXT);

CREATE FUNCTION "fbeds_distribution_authenticate_key"(p_key_id TEXT, p_secret_hash TEXT)
RETURNS TABLE ("tenant_id" TEXT, "agency_id" TEXT, "client_id" TEXT, "credential_id" TEXT, "kind" "DistributionCredentialKind", "scopes" "DistributionApiScope"[],
               "ip_allowlist" TEXT[], "search_per_minute" INTEGER, "check_rate_per_minute" INTEGER, "book_per_minute" INTEGER) AS $$
  SELECT c."tenant_id", dc."agency_id", c."client_id", c."id", c."kind", dc."scopes",
         dc."ip_allowlist", dc."search_per_minute", dc."check_rate_per_minute", dc."book_per_minute"
    FROM "distribution_credentials" c
    JOIN "distribution_clients" dc ON dc."tenant_id" = c."tenant_id" AND dc."id" = c."client_id"
    JOIN "Agency" a ON a."tenant_id" = dc."tenant_id" AND a."id" = dc."agency_id"
    JOIN "tenants" t ON t."id" = c."tenant_id"
   WHERE p_key_id ~ '^[a-z0-9]{20}$' AND p_secret_hash ~ '^[0-9a-f]{64}$'
     AND c."key_id" = p_key_id AND c."secret_hash" = p_secret_hash
     AND c."revoked_at" IS NULL AND (c."expires_at" IS NULL OR c."expires_at" > (now() AT TIME ZONE 'UTC'))
     AND dc."status" = 'ACTIVE' AND a."status" = 'ACTIVE' AND t."status" = 'ACTIVE'
$$ LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION "fbeds_distribution_authenticate_key"(TEXT, TEXT) FROM PUBLIC;

CREATE FUNCTION "fbeds_distribution_authenticate_token"(p_token_hash TEXT)
RETURNS TABLE ("tenant_id" TEXT, "agency_id" TEXT, "client_id" TEXT, "token_id" TEXT, "scopes" "DistributionApiScope"[],
               "ip_allowlist" TEXT[], "search_per_minute" INTEGER, "check_rate_per_minute" INTEGER, "book_per_minute" INTEGER) AS $$
  SELECT x."tenant_id", x."agency_id", x."client_id", x."token_id", x."scopes",
         x."ip_allowlist", x."search_per_minute", x."check_rate_per_minute", x."book_per_minute" FROM (
    SELECT tk."tenant_id", dc."agency_id", tk."client_id", tk."id" AS "token_id",
           ARRAY(SELECT s FROM unnest(tk."scopes") AS s WHERE s = ANY (dc."scopes") ORDER BY s) AS "scopes",
           dc."ip_allowlist", dc."search_per_minute", dc."check_rate_per_minute", dc."book_per_minute"
      FROM "distribution_access_tokens" tk
      JOIN "distribution_credentials" c ON c."tenant_id" = tk."tenant_id" AND c."client_id" = tk."client_id" AND c."id" = tk."credential_id"
      JOIN "distribution_clients" dc ON dc."tenant_id" = tk."tenant_id" AND dc."id" = tk."client_id"
      JOIN "Agency" a ON a."tenant_id" = dc."tenant_id" AND a."id" = dc."agency_id"
      JOIN "tenants" t ON t."id" = tk."tenant_id"
     WHERE p_token_hash ~ '^[0-9a-f]{64}$' AND tk."token_hash" = p_token_hash
       AND tk."revoked_at" IS NULL AND tk."expires_at" > (now() AT TIME ZONE 'UTC')
       AND c."kind" = 'OAUTH_CLIENT' AND c."revoked_at" IS NULL AND (c."expires_at" IS NULL OR c."expires_at" > (now() AT TIME ZONE 'UTC'))
       AND dc."status" = 'ACTIVE' AND a."status" = 'ACTIVE' AND t."status" = 'ACTIVE'
  ) x WHERE cardinality(x."scopes") > 0
$$ LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION "fbeds_distribution_authenticate_token"(TEXT) FROM PUBLIC;

CREATE FUNCTION "fbeds_distribution_issue_token"(p_key_id TEXT, p_secret_hash TEXT, p_token_hash TEXT, p_scopes "DistributionApiScope"[], p_ttl_seconds INTEGER, p_request_id TEXT)
RETURNS TABLE ("outcome" TEXT, "tenant_id" TEXT, "agency_id" TEXT, "client_id" TEXT, "token_id" TEXT, "scopes" "DistributionApiScope"[], "expires_at" TIMESTAMP(3)) AS $$
DECLARE
  v_client RECORD;
  v_scopes "DistributionApiScope"[];
  v_now TIMESTAMP(3) := (now() AT TIME ZONE 'UTC');
  v_token_id TEXT := 'dat_' || replace(gen_random_uuid()::text, '-', '');
BEGIN
  IF p_token_hash IS NULL OR p_token_hash !~ '^[0-9a-f]{64}$' OR p_ttl_seconds IS NULL OR p_ttl_seconds NOT BETWEEN 60 AND 900
     OR (p_request_id IS NOT NULL AND p_request_id !~ '^[A-Za-z0-9._:-]{1,128}$') THEN
    RETURN;
  END IF;
  SELECT k."tenant_id", k."agency_id", k."client_id", k."credential_id", k."scopes" INTO v_client
    FROM "fbeds_distribution_authenticate_key"(p_key_id, p_secret_hash) k WHERE k."kind" = 'OAUTH_CLIENT';
  IF NOT FOUND THEN RETURN; END IF;

  IF p_scopes IS NULL OR cardinality(p_scopes) = 0 THEN
    v_scopes := v_client."scopes";
  ELSIF EXISTS (SELECT 1 FROM unnest(p_scopes) s WHERE NOT (s = ANY (v_client."scopes"))) THEN
    RETURN QUERY SELECT 'invalid_scope'::TEXT, v_client."tenant_id", v_client."agency_id", v_client."client_id", NULL::TEXT, NULL::"DistributionApiScope"[], NULL::TIMESTAMP(3);
    RETURN;
  ELSE
    v_scopes := ARRAY(SELECT DISTINCT s FROM unnest(p_scopes) s ORDER BY s);
  END IF;

  INSERT INTO "distribution_access_tokens" ("id", "tenant_id", "client_id", "credential_id", "token_hash", "scopes", "expires_at", "created_at")
    VALUES (v_token_id, v_client."tenant_id", v_client."client_id", v_client."credential_id", p_token_hash, v_scopes, v_now + make_interval(secs => p_ttl_seconds), v_now);
  INSERT INTO "AuditEvent" ("id", "tenant_id", "actor_type", "action", "entity_type", "entity_id", "payload", "created_at")
    VALUES ('aud_' || replace(gen_random_uuid()::text, '-', ''), v_client."tenant_id", 'SYSTEM', 'distribution.token.issued', 'distribution_access_token', v_token_id,
            jsonb_build_object('clientId', v_client."client_id", 'credentialId', v_client."credential_id", 'agencyId', v_client."agency_id",
                               'scopes', to_jsonb(v_scopes), 'ttlSeconds', p_ttl_seconds, 'requestId', p_request_id), v_now);

  RETURN QUERY SELECT 'issued'::TEXT, v_client."tenant_id", v_client."agency_id", v_client."client_id", v_token_id, v_scopes, v_now + make_interval(secs => p_ttl_seconds);
END $$ LANGUAGE plpgsql SECURITY DEFINER VOLATILE SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION "fbeds_distribution_issue_token"(TEXT, TEXT, TEXT, "DistributionApiScope"[], INTEGER, TEXT) FROM PUBLIC;

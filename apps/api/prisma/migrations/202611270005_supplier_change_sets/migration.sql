-- Supplier change sets (ADR 0061 Amendment 3, slice 4a): a supplier's reviewed submission of availability and stop-sale changes.
--
-- The supplier never writes DailyAvailability, DailyRate or RatePlan. A change set is validated, frozen on submit, reviewed by fBeds staff and applied
-- through the existing calendar edit. This migration adds the three tables, their integrity rules and the supplier permissions only.
--
-- Isolation: forced row-level security on tenant_id. Two permissive policies: a supplier-scoped one (the request set app.current_supplier_id to the
-- caller's organization, so only its rows are visible and writable) and a staff one (no supplier set, tenant-wide, for the review queue in a later step).
-- A request that sets a supplier can therefore never see another organization's rows, whatever the application code does.
--
-- Integrity in the database, for every role: cells freeze once the set leaves DRAFT; the event log is append-only; status moves only along the allowed
-- edges; tenant, supplier, hotel and author never change.
--
-- No privilege is granted here. Per SR-07 runtime grants come only from runtime-role-contract.ts, applied by `ops:provision-api-runtime-role`.
-- Until that runs, the supplier change-set routes fail closed with a database "permission denied".
--
-- Tenant indexes: (tenant_id, supplier_id, status, created_at) for the supplier's list; (tenant_id, status, submitted_at) for the staff queue;
-- (tenant_id, supplier_id, change_set_id) for cells; (tenant_id, supplier_id, change_set_id, created_at) for events.
--
-- Rollback is a later forward migration; do not edit this file once applied. Remove the routes first, then:

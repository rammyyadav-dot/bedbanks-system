-- Status edges and immutable identity. Applies to every role, including the owner.
CREATE OR REPLACE FUNCTION "fbeds_change_set_guard"() RETURNS trigger AS $$
BEGIN
  IF NEW."id" <> OLD."id" OR NEW."tenant_id" <> OLD."tenant_id" OR NEW."supplier_id" <> OLD."supplier_id" OR NEW."hotel_id" <> OLD."hotel_id" OR NEW."created_by_user_id" <> OLD."created_by_user_id" THEN
    RAISE EXCEPTION 'A change set''s identity cannot change' USING ERRCODE = '42501';
  END IF;
  IF NEW."status" <> OLD."status" AND NOT (
       (OLD."status" = 'DRAFT'     AND NEW."status" IN ('SUBMITTED', 'WITHDRAWN'))
    OR (OLD."status" = 'SUBMITTED' AND NEW."status" IN ('WITHDRAWN', 'APPROVED', 'REJECTED', 'APPLIED', 'FAILED'))
    OR (OLD."status" = 'APPROVED'  AND NEW."status" IN ('APPLIED', 'FAILED'))
  ) THEN
    RAISE EXCEPTION 'A change set cannot move from % to %', OLD."status", NEW."status" USING ERRCODE = '42501';
  END IF;
  IF OLD."status" <> 'DRAFT' AND (NEW."cell_count" <> OLD."cell_count" OR NEW."content_sha256" <> OLD."content_sha256" OR NEW."version" <> OLD."version") THEN
    RAISE EXCEPTION 'A submitted change set''s content is frozen' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "supplier_change_sets_guard" BEFORE UPDATE ON "supplier_change_sets"
  FOR EACH ROW EXECUTE FUNCTION "fbeds_change_set_guard"();

-- Cells can be written only while their set is a DRAFT. A cascade from a deleted parent is allowed (the parent is already invisible then).
CREATE OR REPLACE FUNCTION "fbeds_change_set_cells_guard"() RETURNS trigger AS $$
DECLARE parent_status "SupplierChangeSetStatus";
BEGIN
  SELECT "status" INTO parent_status FROM "supplier_change_sets" WHERE "id" = COALESCE(NEW."change_set_id", OLD."change_set_id");
  IF parent_status IS NULL THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'The change set does not exist' USING ERRCODE = '42501';
  END IF;
  IF parent_status <> 'DRAFT' THEN
    RAISE EXCEPTION 'The cells of a submitted change set are frozen' USING ERRCODE = '42501';
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "supplier_change_set_cells_guard" BEFORE INSERT OR UPDATE OR DELETE ON "supplier_change_set_cells"
  FOR EACH ROW EXECUTE FUNCTION "fbeds_change_set_cells_guard"();

-- The history is append-only. The one exception is the foreign-key cascade when the change set itself is deleted (never done by the application).
CREATE OR REPLACE FUNCTION "fbeds_change_set_events_immutable"() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN RETURN OLD; END IF;
  RAISE EXCEPTION 'SupplierChangeSetEvent is append-only' USING ERRCODE = '42501';
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "supplier_change_set_events_immutable" BEFORE UPDATE OR DELETE ON "supplier_change_set_events"
  FOR EACH ROW EXECUTE FUNCTION "fbeds_change_set_events_immutable"();


-- Authoritative inventory and allotment foundation (ADR 0030).
--
-- Adds, as forward-only DDL: explicit inventory modes (ALLOTMENT, FREE_SALE, ON_REQUEST, CLOSED), shared inventory pools with
-- per-night counters, plan membership of a pool, a hotel-local release time, inventory provenance and freshness, and the counter
-- kind recorded on each held night so release, confirmation and cancellation always return to the counter the stock was taken from.
--
-- Existing rows: every DailyAvailability row becomes mode ALLOTMENT, source ADMIN, received_at = migration time and fresh_until NULL
-- (never expires), which is exactly how it behaved before. Every existing InventoryHoldNight is counter_kind PLAN_ROW. Every existing
-- RatePlan gets release_time_local '00:00' and no pool. No existing row changes meaning and nothing is backfilled or guessed.
--
-- Integrity beyond Prisma:
--   * InventoryPoolDay: capacity, sold, held >= 0 and sold + held <= capacity (stock can never go negative or oversell).
--   * Pool name is non-empty and the archived timestamp agrees with the status.
--   * RatePlan.release_time_local is HH:MM 24h; release_days stays >= 0.
--   * InventoryHoldNight: counter_kind POOL_DAY requires pool_day_id and the others forbid it.
--   * DailyAvailability: fresh_until, when set, is after received_at.
--   * A trigger refuses a rate plan in a pool of another hotel or another supplier, or in an archived pool, or a pool plan whose
--     room belongs to another hotel. Tenant mixing is already impossible through the composite foreign keys.
--
-- Tenant indexes: tenant_id leads every non-unique index and every unique key that is used for tenant-scoped lookup.
-- Concurrency: stock is changed only by guarded single-statement UPDATEs (see inventory-counters.ts); the CHECK is the backstop.
--
-- The conditional GRANTs mirror earlier migrations (ADR 0013): they are production privilege changes in effect and need the human
-- decision before this migration is applied to any persistent environment. The restricted hold-expiry role is provisioned by code
-- (hold-expiry-role.ts), which this change extends for the pool-day counter.
--
-- Rollback is a later forward migration; do not edit this file after it is applied. Before dropping, release every pool
-- (set RatePlan.inventory_pool_id to NULL) and note that pool-day stock history would be lost:
--   ALTER TABLE "InventoryHoldNight" DROP COLUMN "pool_day_id", DROP COLUMN "counter_kind";
--   ALTER TABLE "RatePlan" DROP COLUMN "inventory_pool_id", DROP COLUMN "release_time_local";
--   ALTER TABLE "DailyAvailability" DROP COLUMN "inventory_mode", DROP COLUMN "source", DROP COLUMN "received_at", DROP COLUMN "fresh_until";
--   DROP TABLE "InventoryPoolDay", "InventoryPool"; DROP TYPE "InventoryCounterKind", "InventoryPoolStatus", "InventorySource", "InventoryMode";


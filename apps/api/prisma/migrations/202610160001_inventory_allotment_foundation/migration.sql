-- A rate plan may join only an ACTIVE pool of its own hotel and its own supplier.
CREATE OR REPLACE FUNCTION "fbeds_rate_plan_pool_consistency"() RETURNS trigger AS $$
DECLARE
  pool_hotel TEXT; pool_supplier TEXT; pool_state "InventoryPoolStatus";
  plan_hotel TEXT; plan_supplier TEXT;
BEGIN
  IF NEW."inventory_pool_id" IS NULL THEN RETURN NEW; END IF;
  SELECT "hotel_id", "supplier_id", "status" INTO pool_hotel, pool_supplier, pool_state
    FROM "InventoryPool" WHERE "id" = NEW."inventory_pool_id" AND "tenant_id" = NEW."tenant_id";
  IF NOT FOUND THEN RAISE EXCEPTION 'inventory pool not found for this tenant' USING ERRCODE = '23514'; END IF;
  SELECT "hotel_id" INTO plan_hotel FROM "RoomType" WHERE "id" = NEW."room_type_id";
  SELECT "supplier_id" INTO plan_supplier FROM "Contract" WHERE "id" = NEW."contract_id" AND "tenant_id" = NEW."tenant_id";
  IF plan_hotel IS DISTINCT FROM pool_hotel THEN RAISE EXCEPTION 'rate plan and inventory pool belong to different hotels' USING ERRCODE = '23514'; END IF;
  IF plan_supplier IS DISTINCT FROM pool_supplier THEN RAISE EXCEPTION 'rate plan and inventory pool belong to different suppliers' USING ERRCODE = '23514'; END IF;
  IF pool_state <> 'ACTIVE' AND (TG_OP = 'INSERT' OR OLD."inventory_pool_id" IS DISTINCT FROM NEW."inventory_pool_id") THEN
    RAISE EXCEPTION 'inventory pool is archived' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER "RatePlan_pool_consistency" BEFORE INSERT OR UPDATE OF "inventory_pool_id", "room_type_id", "contract_id" ON "RatePlan"
  FOR EACH ROW EXECUTE FUNCTION "fbeds_rate_plan_pool_consistency"();


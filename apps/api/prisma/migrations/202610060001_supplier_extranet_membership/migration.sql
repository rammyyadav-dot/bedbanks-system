-- Supplier extranet membership and private room-note drafts.
-- A membership links an authenticated user to one tenant-owned supplier organization.
-- It does not grant admin supply permissions. A room draft stores a private note only.
-- It does not change Hotel, RoomType, rates, availability, mappings, or publication.
--
-- Tenant indexes: supplier_memberships is listed by (tenant_id, user_id, status)
-- before an organization is chosen, and by (tenant_id, supplier_id) for membership checks.
-- supplier_room_drafts is listed by (tenant_id, supplier_id, hotel_id) and uniquely
-- constrained by (tenant_id, supplier_id, room_type_id).
--
-- Rollback is a later forward migration. Do not edit this file after it is applied.

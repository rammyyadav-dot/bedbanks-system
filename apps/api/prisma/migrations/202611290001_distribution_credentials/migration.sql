-- Authentication lookups. Identity only, never a hash; at most one row; refusals are indistinguishable.
CREATE FUNCTION "fbeds_distribution_authenticate_key"(p_key_id TEXT, p_secret_hash TEXT)
RETURNS TABLE ("tenant_id" TEXT, "agency_id" TEXT, "client_id" TEXT, "credential_id" TEXT, "kind" "DistributionCredentialKind", "scopes" "DistributionApiScope"[]) AS $$
  SELECT c."tenant_id", dc."agency_id", c."client_id", c."id", c."kind", dc."scopes"
    FROM "distribution_credentials" c
    JOIN "distribution_clients" dc ON dc."tenant_id" = c."tenant_id" AND dc."id" = c."client_id"
    JOIN "Agency" a ON a."tenant_id" = dc."tenant_id" AND a."id" = dc."agency_id"
    JOIN "tenants" t ON t."id" = c."tenant_id"
   WHERE p_key_id ~ '^[a-z0-9]{20}$' AND p_secret_hash ~ '^[0-9a-f]{64}$'
     AND c."key_id" = p_key_id AND c."secret_hash" = p_secret_hash
     AND c."revoked_at" IS NULL AND (c."expires_at" IS NULL OR c."expires_at" > (now() AT TIME ZONE 'UTC'))
     AND dc."status" = 'ACTIVE' AND a."status" = 'ACTIVE' AND t."status" = 'ACTIVE'
$$ LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION "fbeds_distribution_authenticate_key"(TEXT, TEXT) FROM PUBLIC;

CREATE FUNCTION "fbeds_distribution_authenticate_token"(p_token_hash TEXT)
RETURNS TABLE ("tenant_id" TEXT, "agency_id" TEXT, "client_id" TEXT, "token_id" TEXT, "scopes" "DistributionApiScope"[]) AS $$
  SELECT x."tenant_id", x."agency_id", x."client_id", x."token_id", x."scopes" FROM (
    SELECT tk."tenant_id", dc."agency_id", tk."client_id", tk."id" AS "token_id",
           ARRAY(SELECT s FROM unnest(tk."scopes") AS s WHERE s = ANY (dc."scopes") ORDER BY s) AS "scopes"
      FROM "distribution_access_tokens" tk
      JOIN "distribution_credentials" c ON c."tenant_id" = tk."tenant_id" AND c."client_id" = tk."client_id" AND c."id" = tk."credential_id"
      JOIN "distribution_clients" dc ON dc."tenant_id" = tk."tenant_id" AND dc."id" = tk."client_id"
      JOIN "Agency" a ON a."tenant_id" = dc."tenant_id" AND a."id" = dc."agency_id"
      JOIN "tenants" t ON t."id" = tk."tenant_id"
     WHERE p_token_hash ~ '^[0-9a-f]{64}$' AND tk."token_hash" = p_token_hash
       AND tk."revoked_at" IS NULL AND tk."expires_at" > (now() AT TIME ZONE 'UTC')
       AND c."kind" = 'OAUTH_CLIENT' AND c."revoked_at" IS NULL AND (c."expires_at" IS NULL OR c."expires_at" > (now() AT TIME ZONE 'UTC'))
       AND dc."status" = 'ACTIVE' AND a."status" = 'ACTIVE' AND t."status" = 'ACTIVE'
  ) x WHERE cardinality(x."scopes") > 0
$$ LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public, pg_temp;
REVOKE ALL ON FUNCTION "fbeds_distribution_authenticate_token"(TEXT) FROM PUBLIC;

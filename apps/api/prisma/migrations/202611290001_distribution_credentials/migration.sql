-- Value rules. Arrays are NOT NULL here because Prisma cannot declare it on a list. created_at comes from the database clock and
-- revoked_at/expires_at from the application's, so no rule compares them to the millisecond: the token cap (one hour) leaves the
-- issuer (15-minute tokens, step 2) far more than any clock skew.
ALTER TABLE "distribution_clients" ADD CONSTRAINT "distribution_clients_values_check" CHECK (
  length(btrim("name")) BETWEEN 1 AND 100
  AND "scopes" IS NOT NULL AND cardinality("scopes") BETWEEN 1 AND 5
  AND "search_per_minute" BETWEEN 1 AND 10000 AND "check_rate_per_minute" BETWEEN 1 AND 10000 AND "book_per_minute" BETWEEN 1 AND 10000
  AND "ip_allowlist" IS NOT NULL AND cardinality("ip_allowlist") <= 50);
-- Each allowlist entry must parse as a CIDR block; an invalid entry makes the cast, and so the write, fail.
ALTER TABLE "distribution_clients" ADD CONSTRAINT "distribution_clients_ip_allowlist_cidr_check" CHECK (("ip_allowlist"::cidr[]) IS NOT NULL);

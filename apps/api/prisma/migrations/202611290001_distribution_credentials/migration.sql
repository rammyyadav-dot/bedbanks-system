-- B2B distribution API credentials (ADR 0075, amendment 3): partner clients, their API keys / OAuth client secrets, and OAuth access tokens.
--
-- Machine partners authenticate before any tenant is known. No role reads these tables to do that. Two SECURITY DEFINER functions take a
-- SHA-256 hash, compare it inside the database and return identity only (tenant, agency, client, scopes), at most one row:
--   fbeds_distribution_authenticate_key(key_id, secret_hash)   for an API key or an OAuth client secret;
--   fbeds_distribution_authenticate_token(token_hash)          for an OAuth access token.
-- Every refusal looks the same (no row): unknown key, wrong secret, revoked or expired credential or token, a client that is not ACTIVE, a
-- suspended or inactive agency, a suspended tenant, or malformed input. A token's scopes are cut to the client's current scopes at every
-- lookup, and revoking the OAuth credential that minted a token stops the token. The hashes are never readable by any restricted role.
--
-- Like fbeds_booking_due_tenants (ADR 0039) and the compliance scope functions (ADR 0067), the functions read across tenants as their owner
-- and so rely on the migration owner bypassing forced RLS (the observed production owner has BYPASSRLS). If it did not, they would return
-- no row and every partner request would be refused: the failure is closed.
--
-- Isolation: forced row-level security on tenant_id = fbeds_current_tenant_id() on all three tables, for every role.
-- Integrity, enforced for every role by triggers and checks: keys, hashes, ownership and expiry never change; revocation is one-way;
-- a client never leaves REVOKED; credentials are never deleted (revoke instead); a token lives at most one hour and is deletable only a day
-- after it expired (a later purge job); a token can only belong to a credential of the same client (composite foreign key).
--
-- No privilege is granted here. Per SR-07 runtime grants come only from runtime-role-contract.ts. EXECUTE on the two functions is added there
-- with the guard that calls them (step 2); until then nothing in the API can authenticate a partner.
--
-- Tenant indexes: clients (tenant_id, agency_id, status) and unique (tenant_id, agency_id, name); credentials (tenant_id, client_id);
-- tokens (tenant_id, client_id, expires_at) and (tenant_id, credential_id). Global unique lookups by design, used only inside the functions:
-- credentials.key_id and tokens.token_hash.
--
-- Rollback is a later forward migration; do not edit this file once applied. With no route using them:
--   DROP FUNCTION "fbeds_distribution_authenticate_token"(TEXT); DROP FUNCTION "fbeds_distribution_authenticate_key"(TEXT, TEXT);

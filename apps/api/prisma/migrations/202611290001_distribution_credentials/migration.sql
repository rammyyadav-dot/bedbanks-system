  "key_id" ~ '^[a-z0-9]{20}$' AND "secret_hash" ~ '^[0-9a-f]{64}$'
  AND ("expires_at" IS NULL OR "expires_at" > "created_at"));
ALTER TABLE "distribution_access_tokens" ADD CONSTRAINT "distribution_access_tokens_values_check" CHECK (
  "token_hash" ~ '^[0-9a-f]{64}$' AND "scopes" IS NOT NULL AND cardinality("scopes") BETWEEN 1 AND 5
  AND "expires_at" > "created_at" AND "expires_at" <= "created_at" + INTERVAL '1 hour');

-- Integrity triggers (every role, including the owner).
CREATE FUNCTION "fbeds_distribution_client_guard"() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'distribution clients are never deleted; revoke instead' USING ERRCODE = 'check_violation'; END IF;
  IF NEW."id" <> OLD."id" OR NEW."tenant_id" <> OLD."tenant_id" OR NEW."agency_id" <> OLD."agency_id"
     OR NEW."created_by_user_id" <> OLD."created_by_user_id" OR NEW."created_at" <> OLD."created_at" THEN
    RAISE EXCEPTION 'distribution client identity is immutable' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD."status" = 'REVOKED' AND NEW."status" <> 'REVOKED' THEN RAISE EXCEPTION 'a revoked distribution client stays revoked' USING ERRCODE = 'check_violation'; END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql SET search_path = public, pg_temp;
CREATE TRIGGER "distribution_clients_guard" BEFORE UPDATE OR DELETE ON "distribution_clients" FOR EACH ROW EXECUTE FUNCTION "fbeds_distribution_client_guard"();

CREATE FUNCTION "fbeds_distribution_credential_guard"() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'distribution credentials are never deleted; revoke instead' USING ERRCODE = 'check_violation'; END IF;
  IF NEW."id" <> OLD."id" OR NEW."tenant_id" <> OLD."tenant_id" OR NEW."client_id" <> OLD."client_id" OR NEW."kind" <> OLD."kind"
     OR NEW."key_id" <> OLD."key_id" OR NEW."secret_hash" <> OLD."secret_hash" OR NEW."expires_at" IS DISTINCT FROM OLD."expires_at"
     OR NEW."created_by_user_id" <> OLD."created_by_user_id" OR NEW."created_at" <> OLD."created_at" THEN
    RAISE EXCEPTION 'distribution credential is immutable except last use and revocation' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD."revoked_at" IS NOT NULL AND NEW."revoked_at" IS DISTINCT FROM OLD."revoked_at" THEN
    RAISE EXCEPTION 'distribution credential revocation is permanent' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql SET search_path = public, pg_temp;
CREATE TRIGGER "distribution_credentials_guard" BEFORE UPDATE OR DELETE ON "distribution_credentials" FOR EACH ROW EXECUTE FUNCTION "fbeds_distribution_credential_guard"();

CREATE FUNCTION "fbeds_distribution_token_guard"() RETURNS trigger AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD."expires_at" < (now() AT TIME ZONE 'UTC') - INTERVAL '1 day' THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'an access token is deletable only a day after it expired' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW."id" <> OLD."id" OR NEW."tenant_id" <> OLD."tenant_id" OR NEW."client_id" <> OLD."client_id" OR NEW."credential_id" <> OLD."credential_id"
     OR NEW."token_hash" <> OLD."token_hash" OR NEW."scopes" <> OLD."scopes" OR NEW."expires_at" <> OLD."expires_at" OR NEW."created_at" <> OLD."created_at" THEN
    RAISE EXCEPTION 'access token is immutable except revocation' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD."revoked_at" IS NOT NULL AND NEW."revoked_at" IS DISTINCT FROM OLD."revoked_at" THEN
    RAISE EXCEPTION 'access token revocation is permanent' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$ LANGUAGE plpgsql SET search_path = public, pg_temp;
CREATE TRIGGER "distribution_access_tokens_guard" BEFORE UPDATE OR DELETE ON "distribution_access_tokens" FOR EACH ROW EXECUTE FUNCTION "fbeds_distribution_token_guard"();


import { darkVariant, normalizeHex } from './color'

/**
 * Theme tokens. `app/theme-tokens.css` is generated from its own light block: the light values are the source of truth
 * (they are the colours the console always shipped with); the dark block is derived by `darkVariant`.
 *   --c-<hex>  a colour that is re-derived for the dark theme
 *   --k-<hex>  a colour that is identical in both themes (dark chrome such as the sidebar, shadows and scrims)
 */
export const TOKENS_FILE = 'app/theme-tokens.css'
export const THEME_COOKIE = 'fbeds_theme'
export const THEME_PREFERENCES = ['light', 'dark', 'system'] as const
export type ThemePreference = (typeof THEME_PREFERENCES)[number]

export function parseThemePreference(value: string | null | undefined): ThemePreference {
  return (THEME_PREFERENCES as readonly string[]).includes(value ?? '') ? (value as ThemePreference) : 'light'
}

const LIGHT_BLOCK = /\/\* light:start \*\/\s*:root\s*\{([^}]*)\}\s*\/\* light:end \*\//

export function parseLightTokens(css: string): Record<string, string> {
  const block = LIGHT_BLOCK.exec(css)?.[1]
  if (!block) throw new Error('theme-tokens.css has no light block')
  const tokens: Record<string, string> = {}
  for (const match of block.matchAll(/(--[kc]-[0-9a-f]{3,8})\s*:\s*(#[0-9a-f]{3,8})\s*;/g)) tokens[match[1]!] = normalizeHex(match[2]!)
  return tokens
}

export function renderTokensCss(light: Record<string, string>): string {
  const names = Object.keys(light).sort()
  const lines = (values: (name: string) => string | null) => names.map((name) => { const v = values(name); return v ? `  ${name}: ${v};` : null }).filter(Boolean).join('\n')
  const dark = lines((name) => name.startsWith('--c-') ? darkVariant(light[name]!) : null)
  return `/* Generated by scripts/generate-theme-tokens.ts from the light block. Edit the light block, then run \`pnpm theme:tokens\`. */
/* light:start */
:root {
${lines((name) => light[name]!)}
}
/* light:end */

/* dark: explicit preference, or system preference when the user chose "system" */
:root[data-theme='dark'] {
  color-scheme: dark;
${dark}
}
@media (prefers-color-scheme: dark) {
  :root[data-theme='system'] {
    color-scheme: dark;
${dark.replace(/^/gm, '  ')}
  }
}
`
}
